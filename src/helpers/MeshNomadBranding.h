// Splits FIRMWARE_VERSION into the two build lines of the boot screen:
//   "v1.18.0-meshnomad.1-b867c51d"       -> "v1.18.0-meshnomad.1", "b867c51d <date>"
//   "v1.18.0-meshnomad.dev.57-b867c51d"  -> "v1.18.0-dev.57",      "b867c51d <date>"
//   "v1.18.0" (local build, no commit)    -> "v1.18.0",             "<date>"
// The commit is cut to 8 chars so the line fits 128 px with the date.
inline void meshnomadBootInfo(const char* fw, const char* build_date,
                              char* version, size_t version_len, char* build, size_t build_len) {
  const char* first = strchr(fw, '-');
  const char* last = strrchr(fw, '-');
  int base_len = first ? (int)(first - fw) : (int)strlen(fw);
  const char* dev = "meshnomad.dev";
  int dev_len = strlen(dev);

  if (first && last > first) {
    const char* channel = first + 1;
    int channel_len = last - channel;
    if (channel_len >= dev_len && strncmp(channel, dev, dev_len) == 0) {
      snprintf(version, version_len, "%.*s-dev%.*s", base_len, fw, channel_len - dev_len, channel + dev_len);
    } else {
      snprintf(version, version_len, "%.*s-%.*s", base_len, fw, channel_len, channel);
    }
  } else {
    snprintf(version, version_len, "%.*s", base_len, fw);
  }

  if (last) {
    snprintf(build, build_len, "%.8s %s", last + 1, build_date);
  } else {
    snprintf(build, build_len, "%s", build_date);
  }
}

