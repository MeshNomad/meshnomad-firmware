#!/usr/bin/env python3
"""Generate the MeshNomad release envs: one firmware per role and board.

Reads the resolved PlatformIO configuration (``pio project config --json-output``)
and writes, between the markers in ``variants/meshnomad/platformio.ini``, one env
per board and role that extends the unchanged MeshCore env:

* ``<board>_mn_rpt`` from ``<board>_repeater``
* ``<board>_mn_rs``  from ``<board>_room_server``
* ``<board>_mn_cmp`` from ``<board>_companion_radio_ble`` (USB added), or
  ``<board>_companion_radio_usb`` when the board has no BLE build

ESP32 boards also get the network layer (``[mn_esp32_net]``); the companion uses
MeshCore's own WiFi (``[mn_cmp_wifi]``, ``[mn_cmp_net]``). Envs whose name ends with ``_`` are
left out, as MeshCore does for its own releases.

Usage: gen_envs.py [--check]   (--check: exit 1 if the file is not up to date)
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "variants" / "meshnomad" / "platformio.ini"
BEGIN = "; >>> generated by tool/meshnomad/gen_envs.py - do not edit below"
END = "; <<< generated"

# Roles produced in this step of the series (C7a: rpt, C7b: +cmp, C7c: +rs).
ROLES: tuple[str, ...] = ("rpt",)

# Operator's choices after the RAM/flash measurement, keyed by (board, role):
# SKIP drops that firmware; NO_NET keeps it without WiFi / network layer.
SKIP: dict[tuple[str, str], str] = {}
NO_NET: dict[tuple[str, str], str] = {}

SUFFIX = {
    "rpt": ("_repeater",),
    "rs": ("_room_server",),
    "cmp": ("_companion_radio_ble", "_companion_radio_usb"),
}


def pio_config() -> list:
    pio = os.environ.get("PIO", "pio")
    out = subprocess.run(
        [pio, "project", "config", "--json-output"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def collect(envs: dict[str, dict]) -> dict[str, dict[str, str]]:
    """board -> {suffix: env}; envs ending with "_" (excluded upstream) are skipped."""
    boards: dict[str, dict[str, str]] = {}
    for env in envs:
        if env.endswith("_") or "_mn_" in env:
            continue
        for suffixes in SUFFIX.values():
            for suffix in suffixes:
                if env.endswith(suffix):
                    boards.setdefault(env[: -len(suffix)], {})[suffix] = env
    return boards


def is_esp32(opts: dict) -> bool:
    return "espressif32" in str(opts.get("platform", ""))


def render_env(board: str, role: str, base: str, opts: dict) -> str:
    net = is_esp32(opts) and (board, role) not in NO_NET
    flags = [f"${{env:{base}.build_flags}}"]
    unflags = [f"${{env:{base}.build_unflags}}"] if "build_unflags" in opts else []
    src = [f"${{env:{base}.build_src_filter}}"]
    libs = [f"${{env:{base}.lib_deps}}"] if "lib_deps" in opts else []
    if role == "cmp" and base.endswith("_companion_radio_ble"):
        flags.append("${mn_cmp_usb.build_flags}")
    if net:
        if role == "cmp":
            if "ENABLE_WIFI_INTERFACE" not in str(opts.get("build_flags", "")):
                flags.append("${mn_cmp_wifi.build_flags}")
            if "helpers/wifi/" not in str(opts.get("build_src_filter", "")):
                src.append("${mn_cmp_wifi.build_src_filter}")
            flags.append("${mn_cmp_net.build_flags}")
        flags.append("${mn_esp32_net.build_flags}")
        src.append("${mn_esp32_net.build_src_filter}")
        libs.append("${mn_esp32_net.lib_deps}")
    flags.append("${mn_release.build_flags}")
    unflags.append("${mn_release.build_unflags}")
    lines = [f"[env:{board}_mn_{role}]", f"extends = env:{base}"]
    for key, values in (
        ("build_flags", flags),
        ("build_unflags", unflags),
        ("build_src_filter", src),
        ("lib_deps", libs),
    ):
        if values:
            lines.append(f"{key} =")
            lines.extend(f"  {v}" for v in values)
    return "\n".join(lines)


def generate(config: list) -> str:
    envs = {name[4:]: dict(opts) for name, opts in config if name.startswith("env:")}
    boards = collect(envs)
    blocks: list[str] = []
    counts = dict.fromkeys(ROLES, 0)
    for board in sorted(boards, key=str.lower):
        for role in ROLES:
            if (board, role) in SKIP:
                continue
            base = next((boards[board][s] for s in SUFFIX[role] if s in boards[board]), None)
            if base is None:
                continue
            blocks.append(render_env(board, role, base, envs[base]))
            counts[role] += 1
    summary = ", ".join(f"{role}={n}" for role, n in counts.items())
    return f"{BEGIN}\n; envs: {summary}\n" + "\n\n".join(blocks) + f"\n{END}\n"


def splice(text: str, generated: str) -> str:
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    if not pattern.search(text):
        sys.exit(f"markers not found in {TARGET}")
    return pattern.sub(lambda _match: generated, text)


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args()
    current = TARGET.read_text()
    # Read MeshCore's envs with the generated block emptied, so a stale block
    # (e.g. one referencing a renamed section) can never break the read.
    TARGET.write_text(splice(current, f"{BEGIN}\n{END}\n"))
    try:
        updated = splice(current, generate(pio_config()))
    finally:
        TARGET.write_text(current)
    if args.check:
        if updated != current:
            print(f"{TARGET.relative_to(ROOT)} is out of date - run tool/meshnomad/gen_envs.py")
            return 1
        print("generated envs up to date")
        return 0
    TARGET.write_text(updated)
    summary = re.search(r"^; envs: .*$", updated, re.M)
    print(summary.group(0) if summary else "written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
