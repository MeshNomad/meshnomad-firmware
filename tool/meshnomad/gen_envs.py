#!/usr/bin/env python3
"""Generate the MeshNomad release envs: one firmware per role and board.

Reads the resolved PlatformIO configuration (``pio project config --json-output``)
and writes, between the markers in ``variants/meshnomad/platformio.ini``, one env
per board and role that extends the unchanged MeshCore env:

* ``<board>_mn_rpt`` from ``<board>_repeater``
* ``<board>_mn_rs``  from ``<board>_room_server``
* ``<board>_mn_cmp`` from ``<board>_companion_radio_ble`` (USB added), or
  ``<board>_companion_radio_usb`` when the board has no BLE build

Only ESP32 boards are generated: MeshNomad firmware needs WiFi for its network layer
(``[mn_esp32_net]``), so boards without it get no MeshNomad firmware. The companion uses
MeshCore's own WiFi (``[mn_cmp_wifi]``, ``[mn_cmp_net]``). Envs whose name ends with ``_`` are
left out, as MeshCore does for its own releases.

The same run writes the supported-boards table into ``README.md``, between its markers.

Usage: gen_envs.py [--check]   (--check: exit 1 if either file is not up to date)
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "variants" / "meshnomad" / "platformio.ini"
BEGIN = "; >>> generated by tool/meshnomad/gen_envs.py - do not edit below"
END = "; <<< generated"
README = ROOT / "README.md"
README_BEGIN = "<!-- >>> supported boards (generated by tool/meshnomad/gen_envs.py) -->"
README_END = "<!-- <<< supported boards -->"

# Roles produced in this step of the series (C7a: rpt, C7b: +cmp, C7c: +rs).
ROLES: tuple[str, ...] = ("rpt", "cmp", "rs")

# Operator's choices after the RAM/flash measurement, keyed by (board, role):
# SKIP drops that firmware (a board that cannot hold the role's full feature set gets
# no MeshNomad firmware for that role); NO_NET keeps it without WiFi / network layer.
SKIP: dict[tuple[str, str], str] = {
    ("Ebyte_EoRa-S3", "cmp"): "BLE, USB, WiFi and network layer exceed flash",
    ("Heltec_v2", "cmp"): "BLE, USB, WiFi and network layer exceed RAM",
    ("LilyGo_T3S3_sx1262", "cmp"): "BLE, USB, WiFi and network layer exceed flash",
    ("LilyGo_T3S3_sx1276", "cmp"): "BLE, USB, WiFi and network layer exceed flash",
    ("LilyGo_TBeam_1W", "cmp"): "BLE, USB, WiFi and network layer exceed flash",
    ("LilyGo_TLora_V2_1_1_6", "cmp"): "BLE, USB, WiFi and network layer exceed RAM",
    ("M5Stack_Unit_C6L", "cmp"): "BLE, USB, WiFi and network layer exceed flash",
    ("Meshadventurer_sx1262", "cmp"): "BLE, USB, WiFi and network layer exceed RAM",
    ("Meshadventurer_sx1268", "cmp"): "BLE, USB, WiFi and network layer exceed RAM",
    ("Station_G2", "cmp"): "MeshCore's own BLE companion exceeds flash",
    ("Station_G3_ESP32", "cmp"): "MeshCore's own BLE companion exceeds flash",
    ("Tbeam_SX1262", "cmp"): "BLE, USB, WiFi and network layer exceed RAM",
    ("Tbeam_SX1276", "cmp"): "BLE, USB, WiFi and network layer exceed RAM",
    ("ThinkNode_M2", "cmp"): "BLE, USB, WiFi and network layer exceed flash",
    ("ThinkNode_M5", "cmp"): "BLE, USB, WiFi and network layer exceed flash",
}
NO_NET: dict[tuple[str, str], str] = {}

SUFFIX = {
    "rpt": ("_repeater",),
    "rs": ("_room_server",),
    "cmp": ("_companion_radio_ble", "_companion_radio_usb"),
}


def pio_config() -> list:
    pio = os.environ.get("PIO", "pio")
    out = subprocess.run(
        [pio, "project", "config", "--json-output"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def collect(envs: dict[str, dict]) -> dict[str, dict[str, str]]:
    """board -> {suffix: env}; envs ending with "_" (excluded upstream) are skipped."""
    boards: dict[str, dict[str, str]] = {}
    for env in envs:
        if env.endswith("_") or "_mn_" in env:
            continue
        for suffixes in SUFFIX.values():
            for suffix in suffixes:
                # MeshCore's build.sh matches role suffixes regardless of case (`_Repeater`).
                if env.lower().endswith(suffix):
                    boards.setdefault(env[: -len(suffix)], {})[suffix] = env
    return boards


def is_esp32(opts: dict) -> bool:
    return "espressif32" in str(opts.get("platform", ""))


def render_env(board: str, role: str, base: str, opts: dict) -> str:
    net = is_esp32(opts) and (board, role) not in NO_NET
    flags = [f"${{env:{base}.build_flags}}"]
    unflags = [f"${{env:{base}.build_unflags}}"] if "build_unflags" in opts else []
    src = [f"${{env:{base}.build_src_filter}}"]
    libs = [f"${{env:{base}.lib_deps}}"] if "lib_deps" in opts else []
    if role == "cmp" and base.endswith("_companion_radio_ble"):
        flags.append("${mn_cmp_usb.build_flags}")
    if net:
        if role == "cmp":
            if "ENABLE_WIFI_INTERFACE" not in str(opts.get("build_flags", "")):
                flags.append("${mn_cmp_wifi.build_flags}")
            if "helpers/wifi/" not in str(opts.get("build_src_filter", "")):
                src.append("${mn_cmp_wifi.build_src_filter}")
            flags.append("${mn_cmp_net.build_flags}")
        flags.append("${mn_esp32_net.build_flags}")
        src.append("${mn_esp32_net.build_src_filter}")
        libs.append("${mn_esp32_net.lib_deps}")
    flags.append("${mn_release.build_flags}")
    unflags.append("${mn_release.build_unflags}")
    lines = [f"[env:{board}_mn_{role}]", f"extends = env:{base}"]
    for key, values in (
        ("build_flags", flags),
        ("build_unflags", unflags),
        ("build_src_filter", src),
        ("lib_deps", libs),
    ):
        if values:
            lines.append(f"{key} =")
            lines.extend(f"  {v}" for v in values)
    return "\n".join(lines)


def generate(config: list) -> tuple[str, dict[str, set[str]]]:
    """The generated ini block and, per board, the roles it gets a MeshNomad firmware for."""
    envs = {name[4:]: dict(opts) for name, opts in config if name.startswith("env:")}
    boards = collect(envs)
    blocks: list[str] = []
    released: dict[str, set[str]] = {}
    counts = dict.fromkeys(ROLES, 0)
    for board in sorted(boards, key=str.lower):
        for role in ROLES:
            if (board, role) in SKIP:
                continue
            base = next((boards[board][s] for s in SUFFIX[role] if s in boards[board]), None)
            if base is None or not is_esp32(envs[base]):
                continue
            blocks.append(render_env(board, role, base, envs[base]))
            released.setdefault(board, set()).add(role)
            counts[role] += 1
    summary = ", ".join(f"{role}={n}" for role, n in counts.items())
    return f"{BEGIN}\n; envs: {summary}\n" + "\n\n".join(blocks) + f"\n{END}\n", released


def render_table(released: dict[str, set[str]]) -> str:
    lines = [README_BEGIN, "| Board | Repeater | Companion | Room server |", "|---|---|---|---|"]
    for board in sorted(released, key=str.lower):
        marks = " | ".join("✓" if role in released[board] else "—" for role in ROLES)
        lines.append(f"| `{board}` | {marks} |")
    return "\n".join([*lines, README_END]) + "\n"


def splice(text: str, generated: str, begin: str = BEGIN, end: str = END) -> str:
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end) + r"\n?", re.S)
    if not pattern.search(text):
        sys.exit(f"markers not found: {begin}")
    return pattern.sub(lambda _match: generated, text)


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args()
    current = TARGET.read_text()
    # Read MeshCore's envs with the generated block emptied, so a stale block
    # (e.g. one referencing a renamed section) can never break the read.
    TARGET.write_text(splice(current, f"{BEGIN}\n{END}\n"))
    try:
        block, released = generate(pio_config())
        updated = splice(current, block)
    finally:
        TARGET.write_text(current)
    readme = README.read_text()
    readme_updated = splice(readme, render_table(released), README_BEGIN, README_END)
    if args.check:
        stale = [p for p, old, new in ((TARGET, current, updated), (README, readme, readme_updated))
                 if old != new]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date - run tool/meshnomad/gen_envs.py")
        if stale:
            return 1
        print("generated envs and supported boards up to date")
        return 0
    TARGET.write_text(updated)
    README.write_text(readme_updated)
    summary = re.search(r"^; envs: .*$", updated, re.M)
    print(summary.group(0) if summary else "written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
